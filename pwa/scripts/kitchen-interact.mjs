import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('/opt/node-tools/node_modules/playwright');
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 412, height: 915 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e));
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.type() + ': ' + m.text()); });
await page.goto('http://localhost:5199/kitchen-sink.html', { waitUntil: 'networkidle' });
await page.getByLabel('More').click();
await page.waitForTimeout(300);
await page.screenshot({ path: '/tmp/ks-menu.png' });
await page.getByRole('menuitem', { name: 'Settings' }).click();
await page.waitForTimeout(300);
await page.getByRole('button', { name: 'Sheet', exact: true }).scrollIntoViewIfNeeded();
await page.getByRole('button', { name: 'Sheet', exact: true }).click();
await page.waitForTimeout(400);
await page.screenshot({ path: '/tmp/ks-sheet.png' });
console.log('history after sheet:', await page.evaluate(() => history.state?.owDepth));
await page.goBack();
await page.waitForTimeout(400);
console.log('sheet closed by back:', (await page.locator('.m3-sheet').count()) === 0);
await page.getByRole('button', { name: 'Dialog', exact: true }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: '/tmp/ks-dialog.png' });
await page.getByRole('button', { name: 'Delete', exact: true }).click();
await page.waitForTimeout(300);
await page.getByRole('button', { name: 'Push screen' }).click();
await page.waitForTimeout(400);
await page.screenshot({ path: '/tmp/ks-pushed.png' });
await page.getByLabel('Back').click();
await page.waitForTimeout(400);
console.log('pushed closed:', (await page.locator('.m3-overlay-screen').count()) === 0, 'depth', await page.evaluate(() => history.state?.owDepth));
console.log(errors.length ? 'errors:\n' + errors.join('\n') : 'no errors');
await browser.close();
