// Generates src/ui/m3/iconData.ts from src/ui/m3/icons.txt: one icon per
// line as "<style>/<name>" (style: round | outlined | filled | sharp), so
// only the icons the app uses are bundled rather than all 2,000.
//
//   node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const list = readFileSync(join(root, 'src/ui/m3/icons.txt'), 'utf8')
  .split('\n')
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith('#'));

const seen = new Set();
const entries = [];
for (const line of list) {
  const [style, name] = line.includes('/') ? line.split('/') : ['round', line];
  const key = style === 'round' ? name : `${name}_${style}`;
  if (seen.has(key)) continue;
  seen.add(key);
  const file = join(root, 'node_modules/@material-design-icons/svg', style, `${name}.svg`);
  let svg;
  try {
    svg = readFileSync(file, 'utf8');
  } catch {
    console.error(`no such icon: ${style}/${name}`);
    process.exitCode = 1;
    continue;
  }
  const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  entries.push([key, inner]);
}
entries.sort((a, b) => (a[0] < b[0] ? -1 : 1));
const out = [
  '// Generated by scripts/gen-icons.mjs from icons.txt. Do not edit.',
  '// Material Symbols / Material Icons, Apache-2.0.',
  'export const iconData: Record<string, string> = {',
  ...entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`),
  '};',
  '',
  'export type IconName = keyof typeof iconData;',
  '',
].join('\n');
writeFileSync(join(root, 'src/ui/m3/iconData.ts'), out);
console.log(`wrote ${entries.length} icons`);
